-- Delta Script Hub database setup (Supabase)
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.scripts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 90),
  category text not null check (char_length(category) between 1 and 40),
  description text not null default '' check (char_length(description) <= 500),
  script_url text,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
alter table public.admins enable row level security;
alter table public.scripts enable row level security;
create policy "Admins read own membership" on public.admins for select to authenticated using (user_id = auth.uid());
create policy "Public reads scripts" on public.scripts for select to anon, authenticated using (true);
create policy "Admins add scripts" on public.scripts for insert to authenticated with check (
 created_by = auth.uid() and exists(select 1 from public.admins a where a.user_id=auth.uid())
);
create policy "Admins update scripts" on public.scripts for update to authenticated using (
 exists(select 1 from public.admins a where a.user_id=auth.uid())
) with check (exists(select 1 from public.admins a where a.user_id=auth.uid()));
create policy "Admins delete scripts" on public.scripts for delete to authenticated using (
 exists(select 1 from public.admins a where a.user_id=auth.uid())
);
grant usage on schema public to anon, authenticated;
grant select on public.scripts to anon, authenticated;
grant insert, update, delete on public.scripts to authenticated;
grant select on public.admins to authenticated;
grant usage, select on sequence public.scripts_id_seq to authenticated;

